export function getProtocolById(id: string): Protocol | undefined {
  return protocols.find((p) => p.id === id);
}

export function getProtocolsByIndication(indication: string): Protocol[] {
  return protocols.filter((p) =>
    p.indication.toLowerCase().includes(indication.toLowerCase())
   );
}
